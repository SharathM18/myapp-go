// Constructor and returning a pointer to zerolog.Logger for Dependency Injection
func NewLogger(cfg *config.Config) *zerolog.Logger {

	// 1. Parse log level (debug, info, warn, error)
	level, err := zerolog.ParseLevel(strings.ToLower(cfg.Observability.Logging.Level))
	if err != nil {
		level = zerolog.InfoLevel
	}

	// 2. Determine output format:
	// Console format for development/local, JSON format for production/staging (unless explicitly overridden)
	// Zerolog’s default behavior is raw, high-performance JSON.
	var output io.Writer = os.Stdout
	if cfg.Observability.Logging.Format == "console" && cfg.Primary.Env == "local" {
		output = zerolog.ConsoleWriter{
			Out:        os.Stdout,
			TimeFormat: time.RFC3339,
		}
	}

	// 3. Construct and return the logger instance directly
	logger := zerolog.New(output).
		Level(level).
		With().
		Timestamp().
		Caller().
		Logger()

	// 4. Attach OpenTelemetry Hook if OTel Logs are enabled via configuration
	// This intercepts all logger calls and forwards them to the OTel LoggerProvider
	// if cfg.Observability.OTel.Enabled && cfg.Observability.OTel.LogsEnabled {
	// 	otelHook := otelzerolog.NewHook(cfg.Observability.OTel.ServiceName)
	// 	logger = logger.Hook(otelHook)
	// }

	logger.Info().
		Str("level", cfg.Observability.Logging.Level).
		Str("format", cfg.Observability.Logging.Format).
		Str("env", cfg.Primary.Env).
		Bool("otel_logs_enabled", cfg.Observability.OTel.LogsEnabled).
		Msg("Logger initialized successfully")

	// Return a pointer
	return &logger
}

// WithTraceContext takes an injected zerolog.Logger and enriches it with active
// OpenTelemetry Trace ID and Span ID from the context.
func WithTraceContext(ctx context.Context, logger zerolog.Logger) zerolog.Logger {
	// It looks inside the ctx object to find the active OpenTelemetry Span
	spanCtx := trace.SpanFromContext(ctx).SpanContext()

	if spanCtx.IsValid() {
		return logger.With().
			Str("trace_id", spanCtx.TraceID().String()).
			Str("span_id", spanCtx.SpanID().String()).
			Logger()
	}
	return logger
}

// PgxLogger bridges PostgreSQL (PGX) query logs into Zerolog and injects Trace Context.
type PgxLogger struct {
	Logger zerolog.Logger
}

// NewPgxLogger wraps (like Adapter) our Zerolog instance into a PGX-compatible trace logger.
func NewPgxLogger(logger *zerolog.Logger, level zerolog.Level) *PgxLogger {
	zLogger := logger.
		Level(level).
		With().
		Str("component", "database").
		Logger()

	return &PgxLogger{Logger: zLogger}
}

// Log implements the pgx/v5 tracelog.Logger interface.
// It automatically intercepts database queries, formats SQL/JSON, and injects active Trace IDs from context.
// Called by PGX internally and Log function name is must
func (p *PgxLogger) Log(ctx context.Context, level tracelog.LogLevel, msg string, data map[string]any) {

	// 1. Convert PGX level to Zerolog level
	zLevel := GetPgxToZerologLevel(level)

	// 2. Build log event using the query's context to extract Trace ID & Span ID
	event := p.Logger.WithLevel(zLevel).Ctx(ctx)
	spanCtx := trace.SpanFromContext(ctx).SpanContext()
	if spanCtx.IsValid() {
		event = event.
			Str("trace_id", spanCtx.TraceID().String()).
			Str("span_id", spanCtx.SpanID().String()) // database Span ID, not the parent HTTP Span ID
	}

	// 3. This loop unpacks the `sql`, `args`, `time`, and `pid` generated by the pgx driver
	for k, v := range data {
		switch val := v.(type) {
		case string:
			if len(val) > 300 {
				event = event.Str(k, val[:300]+"...") // Truncate huge SQL statements
			} else {
				event = event.Str(k, val)
			}
		case []byte:
			if json.Valid(val) {
				event = event.RawJSON(k, val)
			} else {
				event = event.Bytes(k, val)
			}
		default:
			event = event.Interface(k, v)
		}
	}

	event.Msg(msg)
}

// Map PGX log level to Zerolog level
func GetPgxToZerologLevel(level tracelog.LogLevel) zerolog.Level {
	switch level {
	case tracelog.LogLevelTrace, tracelog.LogLevelDebug:
		return zerolog.DebugLevel
	case tracelog.LogLevelInfo:
		return zerolog.InfoLevel
	case tracelog.LogLevelWarn:
		return zerolog.WarnLevel
	case tracelog.LogLevelError:
		return zerolog.ErrorLevel
	default:
		return zerolog.Disabled
	}
}

// Map Zerolog level to PGX log level
func GetZerologLevelToPgx(level zerolog.Level) tracelog.LogLevel {
	switch level {
	case zerolog.DebugLevel:
		return tracelog.LogLevelDebug
	case zerolog.InfoLevel:
		return tracelog.LogLevelInfo
	case zerolog.WarnLevel:
		return tracelog.LogLevelWarn
	case zerolog.ErrorLevel:
		return tracelog.LogLevelError
	default:
		return tracelog.LogLevelNone
	}
}
